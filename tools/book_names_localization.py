def get_localized_book_names(filename_or_prefix: str) -> dict[int, str] | None:
    """Detect translation language from file prefix and return book ID -> name mapping."""
    prefix = filename_or_prefix.lower()

    if prefix.startswith("eng_") or prefix.startswith("eng"):
        # English: we can use a dummy or let caller use eng_name field.
        # But we'll return None so caller knows to use the 'eng_name' column.
        return None
    elif prefix.startswith("lat_") or prefix.startswith("lat"):
        return LATIN_BOOKS
    elif prefix.startswith("grk_") or prefix.startswith("grk"):
        return GREEK_BOOKS
    elif prefix.startswith("heb_") or prefix.startswith("heb"):
        return HEBREW_BOOKS
    elif prefix.startswith("aram_pes") or "pes" in prefix:
        return ARAMAIC_SYRIAC_BOOKS
    elif prefix.startswith("aram_") or prefix.startswith("aram"):
        return ARAMAIC_HEBREW_BOOKS
    elif prefix.startswith("ja_") or prefix.startswith("jap"):
        return JAPANESE_BOOKS
    elif prefix.startswith("zh_chns") or "chns" in prefix or "lzzs" in prefix:
        return CHINESE_SIMPLIFIED_BOOKS
    elif (
        prefix.startswith("zh_")
        or "chnt" in prefix
        or "ckjv" in prefix
        or "lzz" in prefix
    ):
        return CHINESE_TRADITIONAL_BOOKS

    return None
